// faces.h - PixelPal pixel-art faces, 16x16 1-bit bitmaps.
// Each face is 32 bytes (16 rows of 16 bits, MSB = leftmost pixel).
// Draw your own: bit set = pixel on.

#pragma once
#include <stdint.h>

#define FACE_W 16
#define FACE_H 16
#define FACE_BYTES 32

// happy - the default "hey there" face
static const uint8_t FACE_HAPPY[FACE_BYTES] = {
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x0E, 0x70,
    0x0E, 0x70, 0x0E, 0x70, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x60, 0x06, 0x30, 0x0C,
    0x1F, 0xF8, 0x07, 0xE0, 0x00, 0x00, 0x00, 0x00,
};

// blink - eyes closed mid-animation
static const uint8_t FACE_BLINK[FACE_BYTES] = {
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x0E, 0x70, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x60, 0x06, 0x30, 0x0C,
    0x1F, 0xF8, 0x07, 0xE0, 0x00, 0x00, 0x00, 0x00,
};

// wow - surprised, mouth open
static const uint8_t FACE_WOW[FACE_BYTES] = {
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x0E, 0x70,
    0x1F, 0xF8, 0x1F, 0xF8, 0x0E, 0x70, 0x00, 0x00,
    0x00, 0x00, 0x03, 0xC0, 0x07, 0xE0, 0x07, 0xE0,
    0x03, 0xC0, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
};

// sleep - zzz
static const uint8_t FACE_SLEEP[FACE_BYTES] = {
    0x00, 0x00, 0x70, 0x0E, 0x38, 0x1C, 0x1C, 0x38,
    0x7F, 0xFE, 0x00, 0x00, 0x00, 0x00, 0x0E, 0x70,
    0x0E, 0x70, 0x00, 0x00, 0x00, 0x00, 0x07, 0xE0,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
};

enum Mood { MOOD_HAPPY, MOOD_WOW, MOOD_SLEEP };

static const uint8_t* face_for_mood(Mood m) {
    switch (m) {
        case MOOD_WOW:   return FACE_WOW;
        case MOOD_SLEEP: return FACE_SLEEP;
        default:         return FACE_HAPPY;
    }
}
